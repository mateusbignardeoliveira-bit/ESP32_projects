#ifndef LINHA_ANALISE_H
#define LINHA_ANALISE_H

#include <Arduino.h>

#include "../hardware/ArrayLinha.h"


// ============================================================
// SITUAÇÃO DA LINHA
// ============================================================

enum LinhaSituacao
{
    LINHA_NORMAL,
    LINHA_DESALINHADA,
    LINHA_EVENTO
};


// ============================================================
// DADOS PRODUZIDOS PELA ANÁLISE
// ============================================================

struct LinhaData
{

    // --------------------------------------------------------
    // Situação geral
    // --------------------------------------------------------

    LinhaSituacao situacao;


    // --------------------------------------------------------
    // Linha detectada pelo analógico
    // --------------------------------------------------------

    bool linhaDetectada;


    // --------------------------------------------------------
    // Posição analógica
    //
    // Negativo = esquerda
    // Positivo = direita
    // --------------------------------------------------------

    float posicao;


    // --------------------------------------------------------
    // Erro para o controlador
    // --------------------------------------------------------

    float erro;


    // --------------------------------------------------------
    // Soma das intensidades
    // --------------------------------------------------------

    float intensidade;


    // --------------------------------------------------------
    // Quantidade de sensores analógicos ativos
    // --------------------------------------------------------

    uint8_t largura;


    // --------------------------------------------------------
    // Dados digitais
    // --------------------------------------------------------

    uint8_t sensoresPretos;


    // --------------------------------------------------------
    // Posição aproximada dos sensores pretos
    //
    // Negativo = esquerda
    // Positivo = direita
    // --------------------------------------------------------

    float posicaoDigital;


    // --------------------------------------------------------
    // Indica que existe evento digital
    // --------------------------------------------------------

    bool eventoDigital;

};


// ============================================================
// CLASSE
// ============================================================

class LinhaAnalise
{

private:

    // ========================================================
    // CALIBRAÇÃO ANALÓGICA
    // ========================================================

    const int branco[8] =
    {
        213,
        180,
        177,
        177,
        181,
        180,
        184,
        213
    };


    const int preto[8] =
    {
        3394,
        2820,
        2979,
        3031,
        2992,
        2763,
        3019,
        3349
    };


    // ========================================================
    // POSIÇÃO FÍSICA DOS SENSORES
    // ========================================================

    const float pesos[8] =
    {
        -7.0f,
        -5.0f,
        -3.0f,
        -1.0f,
         1.0f,
         3.0f,
         5.0f,
         7.0f
    };


    // ========================================================
    // RESULTADO
    // ========================================================

    LinhaData resultado;


    // ========================================================
    // NORMALIZA UM SENSOR ANALÓGICO
    // ========================================================

    float normalizarSensor(
        int valor,
        int indice
    );


    // ========================================================
    // OBTÉM VALORES ANALÓGICOS
    // ========================================================

    void obterValoresAnalogicos(
        const ArrayData& dados,
        int valores[8]
    );


    // ========================================================
    // OBTÉM VALORES DIGITAIS
    // ========================================================

    void obterValoresDigitais(
        const ArrayData& dados,
        uint8_t valores[8]
    );


public:

    // ========================================================
    // CONSTRUTOR
    // ========================================================

    LinhaAnalise();


    // ========================================================
    // ANALISA OS DADOS
    // ========================================================

    void update(
        const ArrayData& dados
    );


    // ========================================================
    // RETORNA RESULTADO
    // ========================================================

    LinhaData getData();

};

#endif