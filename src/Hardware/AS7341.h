#ifndef AS7341_H
#define AS7341_H

#include <Arduino.h>
#include <Wire.h>
#include <Adafruit_AS7341.h>

#include "TCA.h"


// ============================================================
// DADOS DE UM AS7341
// ============================================================

struct AS7341Data
{
    uint16_t F1;
    uint16_t F2;
    uint16_t F3;
    uint16_t F4;

    uint16_t F5;
    uint16_t F6;
    uint16_t F7;
    uint16_t F8;

    uint16_t clear;
    uint16_t nir;

    bool valido;

    unsigned long tempo;
};


// ============================================================
// CLASSE DOS DOIS AS7341
// ============================================================

class AS7341Sensores
{

private:

    // ========================================================
    // TCA9548A
    // ========================================================

    TCA& tca;


    // ========================================================
    // SENSORES
    // ========================================================

    Adafruit_AS7341 sensorDireita;
    Adafruit_AS7341 sensorEsquerda;


    // ========================================================
    // CANAIS DO TCA
    // ========================================================

    static const uint8_t CANAL_DIREITA = 1;
    static const uint8_t CANAL_ESQUERDA = 2;


    // ========================================================
    // CONFIGURAÇÃO DO AS7341
    // ========================================================
    //
    // Configuração anterior:
    //
    // ATIME = 29
    // ASTEP = 599
    //
    // Tempo:
    // 30 * 600 * 2.78us = aproximadamente 50ms
    //
    // Como readAllChannels() faz duas integrações por sensor,
    // isso deixava a aquisição muito lenta.
    //
    // Nova configuração:
    //
    // ATIME = 9
    // ASTEP = 199
    //
    // Tempo:
    // 10 * 200 * 2.78us = aproximadamente 5.56ms
    //
    // ========================================================

    static const uint8_t ATIME = 5;
    static const uint16_t ASTEP = 5;


    // ========================================================
    // GANHO
    // ========================================================

    static const as7341_gain_t GANHO =
        AS7341_GAIN_32X;


    // ========================================================
    // DADOS
    // ========================================================

    AS7341Data dadosDireita;
    AS7341Data dadosEsquerda;


    // ========================================================
    // CONFIGURA SENSOR
    // ========================================================

    bool configurarSensor(
        Adafruit_AS7341& sensor
    );


    // ========================================================
    // ARMAZENA LEITURA
    // ========================================================

    void armazenarLeitura(
        AS7341Data& destino,
        uint16_t* readings
    );


public:

    // ========================================================
    // CONSTRUTOR
    // ========================================================

    AS7341Sensores(
        TCA& controladorTCA
    );


    // ========================================================
    // BEGIN
    // ========================================================

    bool begin();


    // ========================================================
    // UPDATE
    // ========================================================

    bool update();


    // ========================================================
    // GET DIREITA
    // ========================================================

    AS7341Data getDireita();


    // ========================================================
    // GET ESQUERDA
    // ========================================================

    AS7341Data getEsquerda();

};

#endif