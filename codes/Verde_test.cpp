#include <Arduino.h>

#include "hardware/TCA.h"
#include "hardware/AS7341.h"
#include "hardware/ArrayLinha.h"
#include "hardware/MotorControlador.h"

#include "sensores/AS7341Analise.h"


// ============================================================
// PINO DO BOTÃO
// ============================================================

const int PINO_BOTAO = 32;


// ============================================================
// VELOCIDADE
// ============================================================

const int VELOCIDADE_ROBO = 200;


// ============================================================
// FRENAGEM
// ============================================================
//
// Velocidade negativa por pouco tempo para compensar
// a inércia do robô.
//
// Começamos com:
//     -100 por 80 ms
//
// Depois podemos ajustar esses dois valores.
// ============================================================

const int VELOCIDADE_FREIO = -1000;

const int TEMPO_FREIO_MS = 100;


// ============================================================
// OBJETOS
// ============================================================

TCA tca;

AS7341Sensores sensoresAS7341(tca);


// ============================================================
// ARRAY
//
// RX = 5
// TX = 18
// ============================================================

ArrayLinha arrayLinha(
    Serial2,
    5,
    18,
    115200
);


// ============================================================
// CONTROLADOR DOS MOTORES
//
// RX = 16
// TX = 17
// ============================================================

MotorControlador motorControlador(
    Serial1,
    16,
    17,
    115200
);


// ============================================================
// ANÁLISE DOS AS7341
// ============================================================

AS7341Analise as7341Analise;


// ============================================================
// ESTADO
// ============================================================

bool verdeDetectado = false;


// ============================================================
// PARAR ROBÔ
// ============================================================

void pararRobo()
{
    motorControlador.stop();
}


// ============================================================
// FREAR E PARAR
// ============================================================
//
// Executado somente quando o verde é detectado.
//
// 1. Inverte os motores brevemente.
// 2. Depois manda STOP.
// 3. O robô permanece parado.
//
// ============================================================

void frearERobotParar()
{
    // --------------------------------------------------------
    // FREIO
    // --------------------------------------------------------

    motorControlador.setSpeed(
        VELOCIDADE_FREIO,
        VELOCIDADE_FREIO,
        VELOCIDADE_FREIO,
        VELOCIDADE_FREIO
    );


    // --------------------------------------------------------
    // MANTÉM O FREIO POR POUCO TEMPO
    // --------------------------------------------------------

    delay(TEMPO_FREIO_MS);


    // --------------------------------------------------------
    // PARADA COMPLETA
    // --------------------------------------------------------

    motorControlador.stop();
}


// ============================================================
// SETUP
// ============================================================

void setup()
{
    // --------------------------------------------------------
    // BOTÃO
    // --------------------------------------------------------

    pinMode(
        PINO_BOTAO,
        INPUT_PULLUP
    );


    // --------------------------------------------------------
    // SEGURANÇA INICIAL
    // --------------------------------------------------------

    motorControlador.stop();


    // --------------------------------------------------------
    // TCA
    // --------------------------------------------------------

    tca.begin();


    // --------------------------------------------------------
    // AS7341
    // --------------------------------------------------------

    if(!sensoresAS7341.begin())
    {
        motorControlador.stop();

        while(true)
        {
            motorControlador.stop();
            delay(100);
        }
    }


    // --------------------------------------------------------
    // ARRAY
    // --------------------------------------------------------

    arrayLinha.begin();


    // --------------------------------------------------------
    // MOTOR
    // --------------------------------------------------------

    motorControlador.begin();


    // --------------------------------------------------------
    // SEGURANÇA FINAL DO SETUP
    // --------------------------------------------------------

    motorControlador.stop();
}


// ============================================================
// LOOP
// ============================================================

void loop()
{
    // ========================================================
    // BOTÃO
    // ========================================================

    if(
        digitalRead(PINO_BOTAO) == LOW
    )
    {
        pararRobo();

        verdeDetectado = false;

        return;
    }


    // ========================================================
    // SE JÁ DETECTOU VERDE
    //
    // Não volta a andar.
    // ========================================================

    if(verdeDetectado)
    {
        pararRobo();

        return;
    }


    // ========================================================
    // ATUALIZA AS7341
    // ========================================================

    sensoresAS7341.update();


    // ========================================================
    // OBTÉM DADOS
    // ========================================================

    AS7341Data dadosEsquerda =
        sensoresAS7341.getEsquerda();

    AS7341Data dadosDireita =
        sensoresAS7341.getDireita();


    // ========================================================
    // ANALISA ESQUERDO
    // ========================================================

    AS7341Resultado esquerda =
        as7341Analise.analisar(
            dadosEsquerda
        );


    // ========================================================
    // ANALISA DIREITO
    // ========================================================

    AS7341Resultado direita =
        as7341Analise.analisar(
            dadosDireita
        );


    // ========================================================
    // DETECÇÃO DE VERDE
    //
    // Qualquer um dos sensores detectando verde
    // é suficiente para parar o robô.
    // ========================================================

    if(
        esquerda.verdeDetectado ||
        direita.verdeDetectado
    )
    {
        verdeDetectado = true;

        // ----------------------------------------------------
        // FREIA E PARA
        // ----------------------------------------------------

        frearERobotParar();

        return;
    }


    // ========================================================
    // MOVIMENTO NORMAL
    // ========================================================

    motorControlador.setSpeed(
        VELOCIDADE_ROBO,
        VELOCIDADE_ROBO,
        VELOCIDADE_ROBO,
        VELOCIDADE_ROBO
    );
}